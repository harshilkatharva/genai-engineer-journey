"""Validator enforcing structural and scoping invariants on research decomposition."""

from __future__ import annotations

import logging

from ..exceptions import DecompositionError
from ..models import EffortLevel, ResearchDecomposition

_logger = logging.getLogger("parallel_research_team.decomposition.validator")


class DecompositionValidator:
    """Validates structural integrity, effort scaling, and boundary disjointness of plans."""

    def validate(
        self,
        decomposition: ResearchDecomposition,
        max_workers: int = 4,
        effort_override: EffortLevel | None = None,
    ) -> None:
        """Validate a generated ResearchDecomposition plan.

        Args:
            decomposition: ResearchDecomposition plan generated by the LLM.
            max_workers: Upper ceiling on permitted worker count.
            effort_override: Optional forced effort level ('direct' or 'parallel_decomposed').

        Raises:
            DecompositionError: If structural, boundary, or effort rules are breached.
        """
        # 1. Non-empty topic and rationale
        if not decomposition.topic.strip():
            raise DecompositionError("Decomposition topic cannot be empty.")
        if not decomposition.rationale.strip():
            raise DecompositionError("Decomposition rationale cannot be empty.")

        # 2. Worker count bounds
        brief_count = len(decomposition.worker_briefs)
        if brief_count < 1:
            raise DecompositionError("Decomposition must contain at least 1 worker brief.")
        if brief_count > max_workers:
            raise DecompositionError(
                f"Generated {brief_count} briefs, exceeding configured max_workers={max_workers}."
            )

        # 3. Effort scaling consistency
        if effort_override is not None and decomposition.effort_level != effort_override:
            raise DecompositionError(
                f"Plan effort_level '{decomposition.effort_level.value}' conflicts with requested "
                f"override '{effort_override.value}'."
            )

        if decomposition.effort_level == EffortLevel.DIRECT and brief_count != 1:
            raise DecompositionError(
                f"DIRECT effort level must produce exactly 1 worker brief, got {brief_count}."
            )

        if decomposition.effort_level == EffortLevel.PARALLEL_DECOMPOSED and brief_count < 2:
            raise DecompositionError(
                f"PARALLEL_DECOMPOSED effort level must produce at least 2 worker briefs, got {brief_count}."
            )

        # 4. Brief uniqueness and validity
        seen_ids: set[str] = set()
        seen_titles: set[str] = set()

        for brief in decomposition.worker_briefs:
            b_id = brief.brief_id.strip()
            if not b_id:
                raise DecompositionError("WorkerBrief brief_id cannot be empty.")
            if b_id in seen_ids:
                raise DecompositionError(f"Duplicate brief_id detected: '{b_id}'.")
            seen_ids.add(b_id)

            title_norm = brief.title.strip().lower()
            if not title_norm:
                raise DecompositionError(f"Brief '{b_id}' must have a non-empty title.")
            if title_norm in seen_titles:
                raise DecompositionError(
                    f"Duplicate brief title detected: '{brief.title}'. Briefs must be distinct."
                )
            seen_titles.add(title_norm)

            if not brief.objective.strip():
                raise DecompositionError(f"Brief '{b_id}' must have a non-empty objective.")

            if not brief.task_boundaries:
                raise DecompositionError(
                    f"Brief '{b_id}' must declare at least one explicit task boundary."
                )

        _logger.info(
            "Decomposition validation passed: %d briefs under %s effort level",
            brief_count,
            decomposition.effort_level.value,
        )
